// Produces test/interop/fixture.json: a fully deterministic Noise transcript (fixed keys and
// ephemerals) of the two handshakes StarkLLM uses plus padded transport messages and a rekey
// check. test/interop/verify_fixture.py replays it with a second, independent implementation
// (the Python library "noiseprotocol"); test/interop.test.js checks the fixture is current.
// Run: npm run interop:generate
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { HandshakeInitiator, HandshakeResponder, keyPairFromSecret } from '../src/noise.js';
import { PROLOGUE_PAIRING, PROLOGUE_SESSION, REKEY_INTERVAL } from '../src/constants.js';
import { toHex, utf8 } from '../src/bytes.js';

const fill = (n) => new Uint8Array(32).fill(n);
export function buildFixture() {
  const keys = {
    initiator_static: keyPairFromSecret(fill(0x11)),
    responder_static: keyPairFromSecret(fill(0x22)),
    initiator_ephemeral: keyPairFromSecret(fill(0x33)),
    responder_ephemeral: keyPairFromSecret(fill(0x44)),
  };
  const psk = fill(0x55);
  const out = { note: 'generated by scripts/generate-interop-fixture.mjs; do not edit', cases: [] };
  for (const [pattern, prologue] of [['IKpsk2', PROLOGUE_PAIRING], ['IK', PROLOGUE_SESSION]]) {
    const use = pattern === 'IKpsk2' ? psk : undefined;
    const I = new HandshakeInitiator({ pattern, prologue, staticKey: keys.initiator_static, remoteStaticPublicKey: keys.responder_static.publicKey, psk: use, ephemeralForTests: keys.initiator_ephemeral });
    const R = new HandshakeResponder({ pattern, prologue, staticKey: keys.responder_static, psk: use, ephemeralForTests: keys.responder_ephemeral });
    const m1 = I.writeFirst(utf8('hello-from-phone'));
    R.readFirst(m1);
    const second = R.writeSecond(utf8('hello-from-pc'));
    const { transport: tI } = I.readSecond(second.packet);
    const tR = second.transport;
    const transport = [];
    const plain = [utf8('ping'), new Uint8Array(300).fill(0x61), utf8('{"id":"1","type":"inbox.list"}')];
    for (const p of plain) {
      transport.push({ from: 'initiator', plaintext_hex: toHex(p), ciphertext_hex: toHex(tI.seal(p)) });
      transport.push({ from: 'responder', plaintext_hex: toHex(p), ciphertext_hex: toHex(tR.seal(p)) });
    }
    // rekey check: REKEY_INTERVAL + 1 further messages from the initiator
    let last = '';
    for (let i = 0; i < REKEY_INTERVAL + 1; i++) last = toHex(tI.seal(new Uint8Array([i & 255])));
    out.cases.push({
      protocol_name: `Noise_${pattern}_25519_ChaChaPoly_BLAKE2s`,
      prologue_hex: toHex(prologue),
      psk_hex: use ? toHex(use) : null,
      initiator_static_secret: toHex(keys.initiator_static.secretKey),
      responder_static_secret: toHex(keys.responder_static.secretKey),
      initiator_ephemeral_secret: toHex(keys.initiator_ephemeral.secretKey),
      responder_ephemeral_secret: toHex(keys.responder_ephemeral.secretKey),
      message1_hex: toHex(m1),
      message1_payload_hex: toHex(utf8('hello-from-phone')),
      message2_hex: toHex(second.packet),
      message2_payload_hex: toHex(utf8('hello-from-pc')),
      handshake_hash_hex: toHex(tI.handshakeHash),
      transport,
      rekey_check: { messages_after_transport: REKEY_INTERVAL + 1, last_ciphertext_hex: last, note: 'payload of message i is the single byte (i mod 256); counting starts after the transport list above' },
    });
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const here = dirname(fileURLToPath(import.meta.url));
  writeFileSync(join(here, '..', 'test', 'interop', 'fixture.json'), JSON.stringify(buildFixture(), null, 1) + '\n');
  console.log('wrote test/interop/fixture.json');
}
