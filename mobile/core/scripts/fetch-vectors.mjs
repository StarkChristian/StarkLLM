// Downloads the public Noise test-vector files and keeps only the vectors for the suite
// StarkLLM uses (Noise_*_25519_ChaChaPoly_BLAKE2s). The reduced files are committed in
// test/vectors/ together with the SHA-256 of the original download, so reviewers can check
// that nothing was edited. Run: npm run vectors:fetch
import { createHash } from 'node:crypto';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '..', 'test', 'vectors');
mkdirSync(out, { recursive: true });

const SOURCES = [
  {
    file: 'cacophony.json',
    url: 'https://raw.githubusercontent.com/centromere/cacophony/master/vectors/cacophony.txt',
    license: 'Unlicense (public domain)',
    note: 'The vector set listed on the Noise wiki ("Test vectors"), generated by cacophony (Haskell).',
  },
  {
    file: 'snow.json',
    url: 'https://raw.githubusercontent.com/mcginty/snow/main/tests/vectors/snow.txt',
    license: 'Apache-2.0 / MIT',
    note: 'Vectors generated by snow (Rust), including the "Noise_*_25519_ChaChaPoly_BLAKE2s" set.',
  },
  {
    file: 'noise-c.json',
    url: 'https://raw.githubusercontent.com/rweather/noise-c/master/tests/vector/noise-c-basic.txt',
    license: 'MIT',
    note: 'Vectors from noise-c (C reference implementation by Rhys Weatherley).',
  },
];

const SUITE = /^Noise_[A-Za-z0-9+]+_25519_ChaChaPoly_BLAKE2s$/;

for (const s of SOURCES) {
  const res = await fetch(s.url);
  if (!res.ok) throw new Error(`${s.url}: HTTP ${res.status}`);
  const text = await res.text();
  const sha256 = createHash('sha256').update(text).digest('hex');
  const all = JSON.parse(text).vectors;
  const kept = all.filter((v) => SUITE.test(v.protocol_name ?? v.name));
  const doc = {
    source: s.url,
    license: s.license,
    note: s.note,
    original_sha256: sha256,
    original_vector_count: all.length,
    kept_filter: 'Noise_*_25519_ChaChaPoly_BLAKE2s',
    vectors: kept,
  };
  writeFileSync(join(out, s.file), JSON.stringify(doc) + '\n');
  console.log(`${s.file}: kept ${kept.length} of ${all.length}`);
}
